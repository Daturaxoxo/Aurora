use image::imageops::FilterType;
use std::fs;
use std::path::Path;

fn main() {
    let pairs = [
        (
            "../../production/assets",
            "../../production/assets/processed",
        ),
        ("../../production/icons", "../../production/icons/processed"),
    ];

    for (source, processed) in pairs.map(|(s, p)| (Path::new(s), Path::new(p))) {
        if source.exists() {
            fs::create_dir_all(processed).unwrap();
            process_directory(source, source, processed);
            prune_orphans(source, processed, processed);
        }
    }

    generate_languages_slint();
    generate_translations_slint();
    generate_character_icons();
    generate_theme_backgrounds();
    generate_game_tiles();
    generate_icon_packs();
    slint_build::compile("../../frontend/main.slint").unwrap();

    #[cfg(target_os = "windows")]
    {
        println!("cargo:rerun-if-changed=main.manifest");
        let mut res = winresource::WindowsResource::new();
        res.set_icon("../../production/icons/logo.ico");
        res.set_manifest_file("main.manifest");
        res.set("CompanyName", "Aurora Team");
        res.set("FileDescription", "Aurora");
        res.set("ProductName", "Aurora");
        res.set("OriginalFilename", "Aurora.exe");
        res.set("LegalCopyright", "Copyright (c) 2026 Daturaxoxo");
        res.compile().unwrap();
    }
}

fn generate_languages_slint() {
    const JSON_PATH: &str = "../../production/Langs/lang-codes.json";
    const SLINT_OUT: &str = "../../frontend/languages.slint";

    println!("cargo:rerun-if-changed={JSON_PATH}");

    let json =
        fs::read_to_string(JSON_PATH).unwrap_or_else(|e| panic!("Could not read {JSON_PATH}: {e}"));
    let langs: Vec<serde_json::Value> =
        serde_json::from_str(&json).unwrap_or_else(|e| panic!("Invalid JSON in {JSON_PATH}: {e}"));

    let names = langs
        .iter()
        .map(|l| {
            let name = l["name"]
                .as_str()
                .unwrap_or_else(|| panic!("Missing \"name\" field in {JSON_PATH}"));
            format!("        \"{name}\"")
        })
        .collect::<Vec<_>>()
        .join(",\n");

    let slint = format!(
        "// AUTO-GENERATED BY BUILD.RS - DO NOT EDIT BY HAND!\n\
         // Edit production/Langs/lang-codes.json instead!\n\
         \n\
         export global Languages {{\n\
             out property <[string]> names: [\n\
         {names},\n\
             ];\n\
         }}\n"
    );

    write_if_changed(Path::new(SLINT_OUT), &slint);
}

fn generate_translations_slint() {
    const LANG_CODES_PATH: &str = "../../production/Langs/lang-codes.json";
    const JSON_PATH: &str = "../../production/Langs/translations.json";
    const SLINT_OUT: &str = "../../frontend/translations.slint";

    println!("cargo:rerun-if-changed={JSON_PATH}");
    println!("cargo:rerun-if-changed={LANG_CODES_PATH}");

    let lang_json = fs::read_to_string(LANG_CODES_PATH)
        .unwrap_or_else(|e| panic!("Could not read {LANG_CODES_PATH}: {e}"));
    let langs: Vec<serde_json::Value> = serde_json::from_str(&lang_json)
        .unwrap_or_else(|e| panic!("Invalid JSON in {LANG_CODES_PATH}: {e}"));
    let codes: Vec<&str> = langs
        .iter()
        .map(|l| {
            l["code"]
                .as_str()
                .unwrap_or_else(|| panic!("Missing \"code\" field in {LANG_CODES_PATH}"))
        })
        .collect();

    let json =
        fs::read_to_string(JSON_PATH).unwrap_or_else(|e| panic!("Could not read {JSON_PATH}: {e}"));
    let entries: Vec<serde_json::Value> =
        serde_json::from_str(&json).unwrap_or_else(|e| panic!("Invalid JSON in {JSON_PATH}: {e}"));

    let mut key_props = Vec::with_capacity(entries.len());
    let mut default_values = Vec::with_capacity(entries.len());

    for (index, entry) in entries.iter().enumerate() {
        let key = entry["key"]
            .as_str()
            .unwrap_or_else(|| panic!("Entry {index} in {JSON_PATH} is missing a \"key\" field"));

        let default_en = entry["en"].as_str().unwrap_or_else(|| {
            panic!("Entry \"{key}\" in {JSON_PATH} is missing its required \"en\" value")
        });

        for code in &codes {
            if *code != "en" && entry.get(*code).and_then(|v| v.as_str()).is_none() {
                println!(
                    "cargo:warning=translations.json: key \"{key}\" has no \"{code}\" value, falling back to \"en\""
                );
            }
        }

        key_props.push(format!(
            "    out property <int> {}: {index};",
            slintify_key(key)
        ));
        default_values.push(format!("        {default_en:?}"));
    }

    let slint = format!(
        "// AUTO-GENERATED BY BUILD.RS - DO NOT EDIT BY HAND!\n\
         // Edit production/Langs/translations.json instead!\n\
         \n\
         export global TrKey {{\n\
         {}\n\
         }}\n\
         \n\
         export global Tr {{\n\
             in property <[string]> values: [\n\
         {},\n\
             ];\n\
         }}\n",
        key_props.join("\n"),
        default_values.join(",\n"),
    );

    write_if_changed(Path::new(SLINT_OUT), &slint);
}

fn write_if_changed(path: &Path, contents: &str) {
    if fs::read_to_string(path).is_ok_and(|existing| existing == contents) {
        return;
    }
    fs::write(path, contents).unwrap_or_else(|e| panic!("Could not write {}: {e}", path.display()));
}

fn generate_character_icons() {
    const SOURCE: &str = "../../production/assets/characters";
    const PROCESSED: &str = "production/assets/processed/characters";
    const HEADER: &str = "// AUTO-GENERATED BY BUILD.RS - DO NOT EDIT BY HAND!\n\
                          // Add a PNG to production/assets/characters/<game> instead!\n";

    println!("cargo:rerun-if-changed={SOURCE}");

    let out_path = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR is not set"))
        .join("character_icons.rs");

    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is not set");
    let processed = Path::new(&manifest_dir)
        .ancestors()
        .nth(2)
        .expect("the crate should live two levels below the repo root")
        .join(PROCESSED);

    let png_rows = |dir: &Path| -> Vec<(String, String)> {
        let mut rows: Vec<(String, String)> = fs::read_dir(dir)
            .into_iter()
            .flatten()
            .filter_map(Result::ok)
            .filter_map(|entry| {
                let path = entry.path();
                if path.extension().and_then(|e| e.to_str()) != Some("png") {
                    return None;
                }
                let slug = path.file_stem()?.to_str()?.to_lowercase();
                Some((slug, path.to_str()?.to_string()))
            })
            .collect();
        rows.sort();
        rows
    };

    let mut games: Vec<(String, Vec<(String, String)>)> = fs::read_dir(&processed)
        .into_iter()
        .flatten()
        .filter_map(Result::ok)
        .filter(|entry| entry.file_type().is_ok_and(|t| t.is_dir()))
        .filter_map(|entry| {
            let game = entry.file_name().to_str()?.to_string();
            Some((game, png_rows(&entry.path())))
        })
        .collect();
    games.sort();

    if games.iter().all(|(_, rows)| rows.is_empty()) {
        println!(
            "cargo:warning=no character icons found in {}",
            processed.display()
        );
    }

    let games = games
        .iter()
        .map(|(game, rows)| {
            let rows = rows
                .iter()
                .map(|(slug, path)| format!("        ({slug:?}, include_bytes!({path:?})),"))
                .collect::<Vec<_>>()
                .join("\n");
            format!("    ({game:?}, &[\n{rows}\n    ]),")
        })
        .collect::<Vec<_>>()
        .join("\n");

    let generated = format!(
        "{HEADER}#[allow(clippy::type_complexity)]\npub static CHARACTER_ICONS: &[(&str, &[(&str, &[u8])])] = &[\n{games}\n];\n"
    );

    fs::write(&out_path, generated)
        .unwrap_or_else(|e| panic!("Could not write {}: {e}", out_path.display()));
}

fn generate_theme_backgrounds() {
    const SOURCE: &str = "../../production/assets/backgrounds";
    const HEADER: &str = "// AUTO-GENERATED BY BUILD.RS - DO NOT EDIT BY HAND!\n\
                          // Add an image to production/assets/backgrounds/ instead!\n";

    println!("cargo:rerun-if-changed={SOURCE}");

    let out_path = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR is not set"))
        .join("theme_backgrounds.rs");

    let mut entries = Vec::new();
    collect_backgrounds(Path::new(SOURCE), Path::new(SOURCE), &mut entries);
    entries.sort();

    if entries.is_empty() {
        println!("cargo:warning=no theme backgrounds found in {SOURCE}");
    }

    let rows = entries
        .iter()
        .map(|(name, path)| format!("    ({name:?}, include_bytes!({path:?})),"))
        .collect::<Vec<_>>()
        .join("\n");

    let generated =
        format!("{HEADER}pub static THEME_BACKGROUNDS: &[(&str, &[u8])] = &[\n{rows}\n];\n");

    fs::write(&out_path, generated)
        .unwrap_or_else(|e| panic!("Could not write {}: {e}", out_path.display()));
}

fn collect_backgrounds(root: &Path, current: &Path, into: &mut Vec<(String, String)>) {
    const SKIPPED: &[&str] = &["game"];
    for entry in fs::read_dir(current).into_iter().flatten().flatten() {
        let path = entry.path();
        let Ok(relative) = path.strip_prefix(root) else {
            continue;
        };

        if path.is_dir() {
            let skipped = relative
                .to_str()
                .is_some_and(|name| SKIPPED.iter().any(|s| s.eq_ignore_ascii_case(name)));
            if !skipped {
                collect_backgrounds(root, &path, into);
            }
            continue;
        }

        let Some(extension) = path.extension().and_then(|e| e.to_str()) else {
            continue;
        };
        if !matches!(
            extension.to_lowercase().as_str(),
            "png" | "jpg" | "jpeg" | "gif"
        ) {
            continue;
        }
        let Some(absolute) = fs::canonicalize(&path)
            .ok()
            .and_then(|p| Some(p.to_str()?.trim_start_matches(r"\\?\").to_string()))
        else {
            continue;
        };

        let name = relative
            .with_extension("")
            .to_string_lossy()
            .replace('\\', "/")
            .to_lowercase();
        into.push((name, absolute));
    }
}

fn generate_game_tiles() {
    const SOURCE: &str = "../../production/assets/backgrounds/game";
    const HEADER: &str = "// AUTO-GENERATED BY BUILD.RS - DO NOT EDIT BY HAND!\n\
                          // Add an image named after the game id to production/assets/backgrounds/game instead!\n";

    println!("cargo:rerun-if-changed={SOURCE}");

    let out_path =
        Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR is not set")).join("game_tiles.rs");

    let mut entries: Vec<(String, String)> = fs::read_dir(SOURCE)
        .into_iter()
        .flatten()
        .filter_map(Result::ok)
        .filter_map(|entry| {
            let path = entry.path();
            let extension = path.extension()?.to_str()?.to_lowercase();
            if !matches!(extension.as_str(), "png" | "jpg" | "jpeg") {
                return None;
            }
            let id = path.file_stem()?.to_str()?.to_lowercase();
            let absolute = fs::canonicalize(&path).ok()?;
            let absolute = absolute.to_str()?.trim_start_matches(r"\\?\").to_string();
            Some((id, absolute))
        })
        .collect();
    entries.sort();

    if entries.is_empty() {
        println!("cargo:warning=no game tiles found in {SOURCE}");
    }

    let rows = entries
        .iter()
        .map(|(id, path)| format!("    ({id:?}, include_bytes!({path:?})),"))
        .collect::<Vec<_>>()
        .join("\n");

    let generated = format!("{HEADER}pub static GAME_TILES: &[(&str, &[u8])] = &[\n{rows}\n];\n");

    fs::write(&out_path, generated)
        .unwrap_or_else(|e| panic!("Could not write {}: {e}", out_path.display()));
}

fn generate_icon_packs() {
    const SOURCE: &str = "../../production/icons/processed";
    const SLINT_OUT: &str = "../../frontend/icons.slint";
    const HEADER: &str = "// AUTO-GENERATED BY BUILD.RS - DO NOT EDIT BY HAND!\n\
                          // Add a PNG to a pack folder under production/icons instead!\n";

    println!("cargo:rerun-if-changed=../../production/icons");

    let mut packs: Vec<(String, Vec<(String, String)>)> = fs::read_dir(SOURCE)
        .into_iter()
        .flatten()
        .filter_map(Result::ok)
        .filter(|entry| entry.path().is_dir())
        .filter_map(|entry| {
            let path = entry.path();
            let name = path.file_name()?.to_str()?.to_lowercase();
            let mut icons = Vec::new();
            collect_icons(&path, &path, &mut icons);
            icons.sort();
            Some((name, icons))
        })
        .filter(|(_, icons)| !icons.is_empty())
        .collect();
    packs.sort();

    if packs.is_empty() {
        println!("cargo:warning=no icon packs found in {SOURCE}");
    }

    let mut slugs: Vec<&str> = packs
        .iter()
        .flat_map(|(_, icons)| icons.iter().map(|(slug, _)| slug.as_str()))
        .collect();
    slugs.sort_unstable();
    slugs.dedup();

    let properties = slugs
        .iter()
        .map(|slug| format!("    in property <image> {};", slintify_key(slug)))
        .collect::<Vec<_>>()
        .join("\n");

    write_if_changed(
        Path::new(SLINT_OUT),
        &format!(
            "{HEADER}\n\
             export global Icons {{\n\
             \x20   in property <color> tint;\n\
             \x20   in property <color> tint-contrast;\n\
             \n\
             {properties}\n\
             }}\n"
        ),
    );

    let table = packs
        .iter()
        .map(|(pack, icons)| {
            let rows = icons
                .iter()
                .map(|(slug, path)| format!("        ({slug:?}, include_bytes!({path:?})),"))
                .collect::<Vec<_>>()
                .join("\n");
            format!("    ({pack:?}, &[\n{rows}\n    ]),")
        })
        .collect::<Vec<_>>()
        .join("\n");

    let setters = slugs
        .iter()
        .map(|slug| {
            format!(
                "        icons.set_{}(image({slug:?}));",
                slintify_key(slug).replace('-', "_")
            )
        })
        .collect::<Vec<_>>()
        .join("\n");

    let generated = format!(
        "{HEADER}\
        #[allow(clippy::type_complexity)]\
         pub static ICON_PACKS: &[(&str, &[(&str, &[u8])])] = &[\n{table}\n];\n\
         \n\
         macro_rules! apply_icons {{\n\
         \x20   ($window:expr, $image:expr, $tint:expr) => {{{{\n\
         \x20       let icons = $window.global::<crate::Icons>();\n\
         \x20       #[allow(unused_mut)]\n\
         \x20       let mut image = $image;\n\
         \x20       let (tint, contrast) = $tint;\n\
         \x20       icons.set_tint(tint);\n\
         \x20       icons.set_tint_contrast(contrast);\n\
         {setters}\n\
         \x20   }}}};\n\
         }}\n"
    );

    let out_path =
        Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR is not set")).join("icon_packs.rs");
    fs::write(&out_path, generated)
        .unwrap_or_else(|e| panic!("Could not write {}: {e}", out_path.display()));
}

fn collect_icons(root: &Path, current: &Path, into: &mut Vec<(String, String)>) {
    for entry in fs::read_dir(current).into_iter().flatten().flatten() {
        let path = entry.path();

        if path.is_dir() {
            collect_icons(root, &path, into);
            continue;
        }

        if path.extension().and_then(|e| e.to_str()) != Some("png") {
            continue;
        }
        let Ok(relative) = path.strip_prefix(root) else {
            continue;
        };
        let Some(absolute) = fs::canonicalize(&path)
            .ok()
            .and_then(|p| Some(p.to_str()?.trim_start_matches(r"\\?\").to_string()))
        else {
            continue;
        };

        let slug = relative
            .with_extension("")
            .to_string_lossy()
            .replace('\\', "/")
            .to_lowercase();
        into.push((slug, absolute));
    }
}

fn slintify_key(key: &str) -> String {
    key.chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '-'
            }
        })
        .collect()
}

fn process_directory(root_source: &Path, current_source: &Path, target_base: &Path) {
    for entry in fs::read_dir(current_source).unwrap() {
        let entry = entry.unwrap();
        let path = entry.path();
        if path == target_base {
            continue;
        }
        let relative = path.strip_prefix(root_source).unwrap();
        let dest_path = target_base.join(relative);

        if path.is_dir() {
            fs::create_dir_all(&dest_path).unwrap();
            process_directory(root_source, &path, target_base);
        } else if path.is_file()
            && let Some(extension) = path.extension().and_then(|os| os.to_str())
        {
            let ext_lower = extension.to_lowercase();
            if ext_lower == "png" || ext_lower == "jpg" || ext_lower == "jpeg" {
                let file_name = path.file_name().and_then(|os| os.to_str()).unwrap_or("");
                if relative.starts_with("backgrounds") || file_name.contains("background") {
                    if !is_up_to_date(&path, &dest_path) {
                        fs::copy(&path, &dest_path).unwrap();
                    }
                    continue;
                }

                let size = processed_size(relative, file_name);
                if is_up_to_date(&path, &dest_path)
                    && image::image_dimensions(&dest_path).is_ok_and(|(w, h)| w.max(h) == size)
                {
                    continue;
                }

                if let Ok(img) = image::open(&path) {
                    let scaled = img.resize(size, size, FilterType::Lanczos3);
                    scaled
                        .save(&dest_path)
                        .expect("Failed to save downsampled asset");
                } else {
                    fs::copy(&path, &dest_path).unwrap();
                }
            }
        }
    }
}

fn processed_size(relative: &Path, file_name: &str) -> u32 {
    if relative.starts_with("characters") {
        return 128;
    }

    let in_settings = relative
        .parent()
        .and_then(Path::file_name)
        .is_some_and(|dir| dir == "settings");
    if !in_settings {
        return 64;
    }

    match file_name {
        // FooterIconButton
        "website.png" | "github.png" | "changelog.png" => 38,
        // TabButton
        _ => 36,
    }
}

fn is_up_to_date(source: &Path, dest: &Path) -> bool {
    let (Ok(source), Ok(dest)) = (fs::metadata(source), fs::metadata(dest)) else {
        return false;
    };

    match (source.modified(), dest.modified()) {
        (Ok(source), Ok(dest)) => dest >= source,
        _ => false,
    }
}

fn prune_orphans(root_source: &Path, target_base: &Path, current: &Path) {
    for entry in fs::read_dir(current).unwrap() {
        let path = entry.unwrap().path();
        let relative = path.strip_prefix(target_base).unwrap();

        if path.is_dir() {
            prune_orphans(root_source, target_base, &path);
            if !root_source.join(relative).exists() {
                let _ = fs::remove_dir(&path);
            }
        } else if !root_source.join(relative).exists() {
            fs::remove_file(&path).unwrap();
        }
    }
}
